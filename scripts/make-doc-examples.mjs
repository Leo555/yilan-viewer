// 生成文档类示例（PDF / EPUB / Word / Excel / PPT），写入 examples/文档/
// 用法：npm run examples:docs（之后再运行 npm run examples 更新清单）
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const JSZip = require('jszip');
const XLSX = require('xlsx');

const out = fileURLToPath(new URL('../examples/文档/', import.meta.url));
await mkdir(out, { recursive: true });
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const zipOut = (zip) => zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE', mimeType: 'application/epub+zip' });

/* ---------- PDF：手写最小 PDF，三页，含大纲中的文字与图形 ---------- */
function makePdf() {
  const pages = [
    ['一览 Sample PDF', 'Page 1 - Introduction', 'This PDF is generated by scripts/make-doc-examples.mjs.', 'Try search (Cmd+F), zoom (A- / A+) and scrolling.'],
    ['Chapter 2', 'Page 2 - Shapes', 'Below are a few rectangles drawn with PDF operators.'],
    ['Chapter 3', 'Page 3 - The End', 'The current page number is kept in the URL (?at=3).'],
  ];
  const objs = [];
  const add = (s) => { objs.push(s); return objs.length; };
  const font = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  const bold = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>');
  const pagesId = objs.length + 1 + pages.length * 2;
  const kids = [];
  pages.forEach(([title, sub, ...lines], i) => {
    const ascii = (t) => t.replace(/[^\x20-\x7e]/g, '').replace(/([()\\])/g, '\\$1');
    let s = `BT /F2 28 Tf 72 740 Td (${ascii(title)}) Tj ET\nBT /F1 16 Tf 72 708 Td (${ascii(sub)}) Tj ET\n`;
    lines.forEach((l, j) => { s += `BT /F1 12 Tf 72 ${670 - j * 20} Td (${ascii(l)}) Tj ET\n`; });
    if (i === 1) {
      const colors = ['0.23 0.51 0.96', '0.49 0.23 0.93', '0.06 0.73 0.51', '0.96 0.62 0.04'];
      colors.forEach((c, k) => { s += `${c} rg ${72 + k * 120} 480 100 100 re f\n`; });
    }
    s += `0.6 g BT /F1 10 Tf 280 40 Td (${i + 1} / ${pages.length}) Tj ET\n`;
    const content = add(`<< /Length ${Buffer.byteLength(s)} >>\nstream\n${s}endstream`);
    kids.push(add(`<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 612 792] /Contents ${content} 0 R /Resources << /Font << /F1 ${font} 0 R /F2 ${bold} 0 R >> >> >>`));
  });
  add(`<< /Type /Pages /Kids [${kids.map((k) => `${k} 0 R`).join(' ')}] /Count ${kids.length} >>`);
  const catalog = add(`<< /Type /Catalog /Pages ${pagesId} 0 R >>`);
  let pdf = '%PDF-1.4\n';
  const offsets = objs.map((o, i) => { const at = Buffer.byteLength(pdf); pdf += `${i + 1} 0 obj\n${o}\nendobj\n`; return at; });
  const xref = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}`;
  pdf += `trailer\n<< /Size ${objs.length + 1} /Root ${catalog} 0 R /Info << /Title (Sample) >> >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(pdf, 'latin1');
}

/* ---------- EPUB ---------- */
async function makeEpub() {
  const chapters = [
    ['第一章　晨雾', ['清晨，城市还没有醒来。', '薄雾笼罩着河面，远处的桥只露出模糊的轮廓。', '他推开窗，冷空气带着潮湿的草木气味涌进屋里。']],
    ['第二章　旧书店', ['街角那家旧书店已经开了三十年。', '店主总说，每一本书都在等待属于它的读者。', '书架间的灯光昏黄，时间在这里走得很慢。']],
    ['第三章　归途', ['傍晚下起了小雨。', '他把那本泛黄的诗集揣进怀里，沿着河岸慢慢往回走。', '雾又起了，但这一次，他知道方向。']],
  ];
  const zip = new JSZip();
  zip.file('mimetype', 'application/epub+zip', { compression: 'STORE' });
  zip.file('META-INF/container.xml', '<?xml version="1.0"?><container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container"><rootfiles><rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/></rootfiles></container>');
  const items = chapters.map((_, i) => `<item id="c${i + 1}" href="c${i + 1}.xhtml" media-type="application/xhtml+xml"/>`).join('');
  const spine = chapters.map((_, i) => `<itemref idref="c${i + 1}"/>`).join('');
  zip.file('OEBPS/content.opf', `<?xml version="1.0" encoding="UTF-8"?><package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="id"><metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:identifier id="id">urn:uuid:7d1c6f2a-0b5e-4c1f-9a51-yilan-sample</dc:identifier><dc:title>雾中小记</dc:title><dc:creator>一览示例</dc:creator><dc:language>zh-CN</dc:language><meta property="dcterms:modified">2026-11-18T00:00:00Z</meta></metadata><manifest><item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/><item id="css" href="style.css" media-type="text/css"/>${items}</manifest><spine>${spine}</spine></package>`);
  zip.file('OEBPS/style.css', 'body{line-height:1.9;font-family:serif} h1{font-size:1.5em;margin:2em 0 1em;text-align:center} p{text-indent:2em;margin:0 0 .6em}');
  zip.file('OEBPS/nav.xhtml', `<?xml version="1.0" encoding="UTF-8"?><html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops"><head><title>目录</title></head><body><nav epub:type="toc"><ol>${chapters.map(([t], i) => `<li><a href="c${i + 1}.xhtml">${t}</a></li>`).join('')}</ol></nav></body></html>`);
  chapters.forEach(([title, paras], i) => {
    const body = Array.from({ length: 6 }, () => paras.map((p) => `<p>${esc(p)}</p>`).join('')).join('');
    zip.file(`OEBPS/c${i + 1}.xhtml`, `<?xml version="1.0" encoding="UTF-8"?><html xmlns="http://www.w3.org/1999/xhtml" lang="zh-CN"><head><title>${title}</title><link rel="stylesheet" href="style.css"/></head><body><h1>${title}</h1>${body}</body></html>`);
  });
  return zipOut(zip);
}

/* ---------- Word ---------- */
async function makeDocx() {
  const p = (text, style) => `<w:p>${style ? `<w:pPr><w:pStyle w:val="${style}"/></w:pPr>` : ''}<w:r><w:t xml:space="preserve">${esc(text)}</w:t></w:r></w:p>`;
  const rich = '<w:p><w:r><w:t xml:space="preserve">支持</w:t></w:r><w:r><w:rPr><w:b/></w:rPr><w:t xml:space="preserve">粗体</w:t></w:r><w:r><w:t xml:space="preserve">、</w:t></w:r><w:r><w:rPr><w:i/></w:rPr><w:t xml:space="preserve">斜体</w:t></w:r><w:r><w:t xml:space="preserve">、</w:t></w:r><w:r><w:rPr><w:u w:val="single"/></w:rPr><w:t xml:space="preserve">下划线</w:t></w:r><w:r><w:t xml:space="preserve">和表格。</w:t></w:r></w:p>';
  const cell = (t, b) => `<w:tc><w:tcPr><w:tcW w:w="3000" w:type="dxa"/></w:tcPr><w:p><w:r>${b ? '<w:rPr><w:b/></w:rPr>' : ''}<w:t>${esc(t)}</w:t></w:r></w:p></w:tc>`;
  const rows = [['季度', '收入（万元）', '同比'], ['Q1', '1,280', '+12%'], ['Q2', '1,460', '+18%'], ['Q3', '1,530', '+9%']];
  const table = `<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="9000" w:type="dxa"/><w:tblBorders><w:top w:val="single" w:sz="4"/><w:left w:val="single" w:sz="4"/><w:bottom w:val="single" w:sz="4"/><w:right w:val="single" w:sz="4"/><w:insideH w:val="single" w:sz="4"/><w:insideV w:val="single" w:sz="4"/></w:tblBorders></w:tblPr>${rows.map((r, i) => `<w:tr>${r.map((c) => cell(c, i === 0)).join('')}</w:tr>`).join('')}</w:tbl>`;
  const body = [
    p('2026 年第三季度工作报告', 'Heading1'),
    p('这是一份由脚本生成的 Word 示例文档，用来演示一览的 .docx 预览能力。'),
    rich,
    p('一、业务概况', 'Heading2'),
    p('本季度整体收入稳步增长，核心产品用户数突破 100 万。'),
    table,
    p('二、下季度计划', 'Heading2'),
    p('1. 完成移动端改版；'),
    p('2. 上线文档在线预览功能；'),
    p('3. 优化首屏加载性能。'),
  ].join('');
  const zip = new JSZip();
  zip.file('[Content_Types].xml', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/><Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/></Types>');
  zip.file('_rels/.rels', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>');
  zip.file('word/_rels/document.xml.rels', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>');
  zip.file('word/styles.xml', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:styles xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:style w:type="paragraph" w:styleId="Heading1"><w:name w:val="heading 1"/></w:style><w:style w:type="paragraph" w:styleId="Heading2"><w:name w:val="heading 2"/></w:style><w:style w:type="table" w:styleId="TableGrid"><w:name w:val="Table Grid"/></w:style></w:styles>');
  zip.file('word/document.xml', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>${body}</w:body></w:document>`);
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}

/* ---------- Excel ---------- */
function makeXlsx() {
  const wb = XLSX.utils.book_new();
  const sales = [['月份', '华北', '华东', '华南', '合计']];
  ['1月', '2月', '3月', '4月', '5月', '6月'].forEach((m, i) => {
    const r = [1200 + i * 80, 1800 + i * 120, 1500 + i * 60];
    sales.push([m, ...r, r.reduce((a, b) => a + b, 0)]);
  });
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(sales), '销售');
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([
    ['工号', '姓名', '部门', '入职日期'],
    ['A001', '张三', '研发', '2021-03-01'],
    ['A002', '李四', '设计', '2022-07-15'],
    ['A003', '王五', '市场', '2023-11-20'],
  ]), '员工');
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([['备注'], ['第二个工作表可以通过底部标签切换。']]), '说明');
  return XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' });
}

/* ---------- PPT ---------- */
async function makePptx() {
  const slides = [
    ['一览：在线预览任何文件', ['纯前端，文件不上传', '支持 PDF、EPUB、Office、代码、媒体']],
    ['为什么做', ['收到附件不想装软件', '想在手机、平板上快速看一眼', '代码要高亮、表格要能翻']],
    ['路线图', ['Q4：文档预览', 'Q1：批注与分享', 'Q2：插件系统']],
  ];
  const ns = 'xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"';
  const sp = (id, paras) => `<p:sp><p:nvSpPr><p:cNvPr id="${id}" name="t${id}"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr><p:spPr/><p:txBody><a:bodyPr/>${paras.map((t) => `<a:p><a:r><a:t>${esc(t)}</a:t></a:r></a:p>`).join('')}</p:txBody></p:sp>`;
  const zip = new JSZip();
  zip.file('[Content_Types].xml', `<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>${slides.map((_, i) => `<Override PartName="/ppt/slides/slide${i + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>`).join('')}</Types>`);
  zip.file('_rels/.rels', '<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="ppt/presentation.xml"/></Relationships>');
  zip.file('ppt/presentation.xml', `<?xml version="1.0" encoding="UTF-8"?><p:presentation ${ns}><p:sldIdLst>${slides.map((_, i) => `<p:sldId id="${256 + i}" r:id="rId${i + 1}"/>`).join('')}</p:sldIdLst><p:sldSz cx="9144000" cy="5143500"/></p:presentation>`);
  zip.file('ppt/_rels/presentation.xml.rels', `<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">${slides.map((_, i) => `<Relationship Id="rId${i + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="slides/slide${i + 1}.xml"/>`).join('')}</Relationships>`);
  slides.forEach(([title, bullets], i) => {
    zip.file(`ppt/slides/slide${i + 1}.xml`, `<?xml version="1.0" encoding="UTF-8"?><p:sld ${ns}><p:cSld><p:spTree><p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr><p:grpSpPr/>${sp(2, [title])}${sp(3, bullets)}</p:spTree></p:cSld></p:sld>`);
  });
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}

const outputs = {
  'sample.pdf': makePdf(),
  'novel.epub': await makeEpub(),
  'report.docx': await makeDocx(),
  'sales.xlsx': makeXlsx(),
  'roadmap.pptx': await makePptx(),
};
for (const [name, buf] of Object.entries(outputs)) await writeFile(out + name, buf);
console.log(`已生成 ${Object.keys(outputs).length} 个文档示例到 examples/文档/`);
